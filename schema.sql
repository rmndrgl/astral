CREATE TABLE drafts (
	uuid  TEXT PRIMARY KEY,
	draft TEXT,
	saved DATETIME,
	created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
	updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
	UNIQUE(uuid)
);

CREATE TABLE dejavus (
	uuid   TEXT PRIMARY KEY,
	dejavu TEXT,
	saved  DATETIME,
	created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
	updated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
	iddraft TEXT,
	FOREIGN KEY (iddraft) REFERENCES drafts(uuid) ON DELETE CASCADE ON UPDATE CASCADE,
	UNIQUE(iddraft)
);
